#include <iostream>
#include <string>
#include <vector>

using namespace std;

class Solution {
public:
    int jump(vector<int>& nums) {
        int n = nums.size();
        if (n <= 1) return 0;

        int jumps = 0;
        int currentEnd = 0;
        int farthest = 0;

        for (int i = 0; i < n - 1; i++) {
            farthest = max(farthest, i + nums[i]);
            if (i == currentEnd) {
                jumps++;
                currentEnd = farthest;
            }
        }

        return jumps;
    }
};

int main(){

    vector<int> nums = {2,3,1,1,4};
    Solution sol;
    int result = sol.jump(nums);
    cout << "Result: " << result << endl;

    return 0;
}
